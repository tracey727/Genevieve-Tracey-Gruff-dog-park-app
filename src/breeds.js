export const BREED_INDEX = [...new Set(names)].sort().map((name) => ({
  name,
  brachycephalic: brachy.has(name),
  doubleCoated: doubleCoated.has(name),
  heatSensitive: brachy.has(name) || doubleCoated.has(name)
}));

export function breedInfo(name) {
  return BREED_INDEX.find((b) => b.name === name) || { name, brachycephalic: false, doubleCoated: false, heatSensitive: false };
}
